<#
.SYNOPSIS
  Regenerates KnownWinUiTypes.txt: every public Microsoft.UI.Xaml* type name in the newest stable and
  experimental Microsoft.WindowsAppSDK.WinUI packages in the NuGet cache.

.DESCRIPTION
  The Surface leaves out a default-xmlns element its own WinUI lacks only when the name is on this list
  (a real type from a newer WinAppSDK). Any other unknown name stays a XAML error, so typos still surface.
  Rerun after a new WinAppSDK ships (restore a project that references it first so the package is cached).
#>
[CmdletBinding()]
param(
    [string]$PackagesRoot = (Join-Path ($env:NUGET_PACKAGES ?? (Join-Path $env:USERPROFILE '.nuget\packages')) 'microsoft.windowsappsdk.winui')
)
$ErrorActionPreference = 'Stop'

$versions = Get-ChildItem $PackagesRoot -Directory | ForEach-Object {
    $core, $pre = $_.Name -split '-', 2
    [pscustomobject]@{ Dir = $_.FullName; Name = $_.Name; Version = [version]$core; Pre = [bool]$pre }
}
$picked = @(
    $versions | Where-Object { -not $_.Pre } | Sort-Object Version -Descending | Select-Object -First 1
    $versions | Where-Object { $_.Pre } | Sort-Object Version -Descending | Select-Object -First 1
) | Where-Object { $_ }
if (-not $picked) { throw "No Microsoft.WindowsAppSDK.WinUI packages under $PackagesRoot." }

$names = [System.Collections.Generic.SortedSet[string]]::new([StringComparer]::Ordinal)
foreach ($p in $picked) {
    foreach ($winmd in Get-ChildItem (Join-Path $p.Dir 'metadata') -Filter '*.winmd') {
        $stream = [IO.File]::OpenRead($winmd.FullName)
        try {
            $pe = [System.Reflection.PortableExecutable.PEReader]::new($stream)
            $md = [System.Reflection.Metadata.PEReaderExtensions]::GetMetadataReader($pe)
            foreach ($h in $md.TypeDefinitions) {
                $t = $md.GetTypeDefinition($h)
                $ns = $md.GetString($t.Namespace)
                $public = ($t.Attributes -band [System.Reflection.TypeAttributes]::VisibilityMask) -eq [System.Reflection.TypeAttributes]::Public
                if ($public -and $ns.StartsWith('Microsoft.UI.Xaml', [StringComparison]::Ordinal)) {
                    [void]$names.Add(($md.GetString($t.Name) -replace '`\d+$', ''))
                }
            }
        }
        finally { $stream.Dispose() }
    }
}

$out = Join-Path $PSScriptRoot 'Surface\KnownWinUiTypes.txt'
$header = "# Generated by Update-KnownWinUiTypes.ps1 from Microsoft.WindowsAppSDK.WinUI $(($picked.Name) -join ', '). Do not edit."
Set-Content -Path $out -Value (@($header) + @($names)) -Encoding utf8NoBOM
Write-Host "Wrote $($names.Count) type names to $out"
